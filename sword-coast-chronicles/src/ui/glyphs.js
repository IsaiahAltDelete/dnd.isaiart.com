// ui/glyphs.js — the kit's bitmap typefaces as pure data: body 5x7, compact 4x6, and the Lombardic display face.
//
// Three faces, one authoring convention: a glyph is a list of rows, '#' lit,
// '.' clear, every row the same width. Row 0 is the top of a capital; each face
// names its baseline row, and letters that dip below it (g j p q y , ;) use the
// rows after. Proportional faces take their advance from the row width, so an
// 'i' is narrow and an 'M' is wide without any separate metrics table.
//
// `buildFace()` normalises a face for the atlas: it pads every glyph to the
// full cell height plus HEAD rows of headroom (accents on capitals sit up
// there, in the line gap, rather than squashing the letter), fills in accented
// letters from their base letter and a mark, and borrows any missing symbol
// from the body face, aligned on the baseline. No imports: data only, safe to
// load in node for tools.

