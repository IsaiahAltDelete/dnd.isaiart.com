/**
 * Normalise a raw glyph (rows array, or `{ at, r }`) to a full-height cell:
 * `rows` is HEAD + cellH strings, all `w` wide.
 */
function normGlyph(raw, cellH) {
  const at = Array.isArray(raw) ? 0 : (raw.at || 0);
  const src = Array.isArray(raw) ? raw : raw.r;
  const w = src.reduce((m, r) => Math.max(m, r.length), 0);
  const blank = '.'.repeat(w);
  const rows = [];
  for (let i = 0; i < HEAD + cellH; i++) {
    const r = src[i - HEAD - at];
    rows.push(r == null ? blank : r.padEnd(w, '.'));
  }
  return { w, rows };
}

/** Put `mark` over glyph `g`: over the x-height for lowercase, into the headroom for capitals. */
function withMark(g, mark, bottomRow, clearAbove) {
  const w = Math.max(g.w, mark[0].length);
  const rows = g.rows.map((r) => r.padEnd(w, '.'));
  // A dotted letter (i, j) loses its dot before it takes an accent.
  if (clearAbove != null) for (let i = 0; i < clearAbove; i++) rows[i] = '.'.repeat(w);
  const mw = mark[0].length;
  const ox = Math.max(0, Math.floor((w - mw) / 2 + 0.5) - (w % 2 === 0 && mw % 2 === 1 ? 1 : 0));
  for (let k = 0; k < mark.length; k++) {
    const ry = bottomRow - (mark.length - 1) + k;
    if (ry < 0 || ry >= rows.length) continue;
    const row = rows[ry].split('');
    for (let c = 0; c < mw; c++) if (mark[k][c] === '#') row[ox + c] = '#';
    rows[ry] = row.join('');
  }
  return { w, rows };
}

/**
 * Build a face from its glyph table.
 *   def: { id, glyphs, cellH, baseline, capH, xTop, lineGap, spacing, mono, spaceW }
 * Returns { ...def, cellW, map: Map(char -> { w, rows }) }.
 */
export function buildFace(def, fallback = null) {
  const map = new Map();
  for (const [ch, raw] of Object.entries(def.glyphs)) map.set(ch, normGlyph(raw, def.cellH));
  for (const [ch, [base, markId]] of Object.entries(ACCENTED)) {
    if (map.has(ch) || !map.has(base)) continue;
    const upper = base !== base.toLowerCase();
    // Capitals carry the mark in the headroom (one clear row above the cap
    // line when the face has room for it); lowercase carry it just over the
    // x-height, where ascenders would be.
    const bottom = upper ? HEAD - 1 : HEAD + def.xTop - 1 - (def.markGap || 0);
    map.set(ch, withMark(map.get(base), MARKS[markId], bottom, upper ? null : HEAD + def.xTop - 1));
  }
  // Borrow symbols this face never drew from the fallback face, sitting on the
  // same baseline, so a heart or an arrow in a heading still prints.
  if (fallback) {
    const dy = def.baseline - fallback.baseline;
    for (const [ch, g] of fallback.map) {
      if (map.has(ch)) continue;
      const rows = [];
      for (let i = 0; i < HEAD + def.cellH; i++) {
        const r = g.rows[i - dy];
        rows.push(r == null ? '.'.repeat(g.w) : r);
      }
      map.set(ch, { w: g.w, rows });
    }
  }
  let cellW = 1;
  for (const g of map.values()) cellW = Math.max(cellW, g.w);
  if (def.spaceW != null) map.set(' ', { w: def.spaceW, rows: Array(HEAD + def.cellH).fill('.'.repeat(def.spaceW)) });
  return { ...def, cellW, map };
}

