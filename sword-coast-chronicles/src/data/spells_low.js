// ---------------------------------------------------------------------------
// deepFreeze — catalogues are shared, never mutated. Instances are cloned.
// ---------------------------------------------------------------------------
function deepFreeze(obj) {
  if (obj === null || typeof obj !== 'object' || Object.isFrozen(obj)) return obj;
  Object.freeze(obj);
  for (const key of Object.getOwnPropertyNames(obj)) deepFreeze(obj[key]);
  return obj;
}

/** Cantrips through 4th-level spells, keyed by id. Frozen. */
export const SPELLS_LOW = deepFreeze(RAW);

// ---------------------------------------------------------------------------
// Small pure helpers (no imports, no state) — convenience for UI and rules.
// ---------------------------------------------------------------------------

/** Every id in this half of the catalogue. */
export const SPELLS_LOW_IDS = Object.freeze(Object.keys(SPELLS_LOW));

/** Ids at a given spell level (0 = cantrip). */
export function lowSpellsAtLevel(level) {
  return SPELLS_LOW_IDS.filter((id) => SPELLS_LOW[id].level === level);
}

/** Ids on a class list, optionally capped at a maximum spell level. */
export function lowSpellsForList(list, maxLevel = 4) {
  return SPELLS_LOW_IDS.filter((id) => SPELLS_LOW[id].level <= maxLevel && SPELLS_LOW[id].lists.includes(list));
}

/** Counts by level, for content audits: { 0:34, 1:59, ... }. */
export function lowSpellCounts() {
  const out = {};
  for (const id of SPELLS_LOW_IDS) {
    const l = SPELLS_LOW[id].level;
    out[l] = (out[l] || 0) + 1;
  }
  return out;
}
