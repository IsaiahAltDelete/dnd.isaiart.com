// Run with tools/shot.mjs --scenario town --script tools/society-check.js.
// Isolated browser state only: exercise real rules, transactions, saves and AI.
const { Game, Party, Stage, Save } = SC;
const { noteDeed } = await import('/src/rules/deeds.js');
const { localStanding, socialRegion, npcDisposition, socialGreeting, rememberNPC } = await import('/src/rules/reputation.js');
const { reportAssault, payFine, witnessesNear } = await import('/src/rules/crime.js');
const { NPCEntity } = await import('/src/world/entity.js');
const { ShopScene } = await import('/src/ui/shop.js');
const { DialogueScene } = await import('/src/ui/dialogue.js');
const { TileMap, TF } = await import('/src/world/tilemap.js');
const scene = Game.scenes.find(s => s.id === 'overworld');
const st = Game.state, map = scene.map;
const checks = [], shots = [];
const check = (name, ok, detail) => { checks.push({ name, ok: !!ok, detail }); if (!ok) throw new Error(name + ': ' + JSON.stringify(detail)); };
const capture = id => { Game._draw(); shots.push({ id, x: 0, y: 0, url: Stage.snapshot() }); };
const buy = (shop, id) => shop._buyRows().find(r => r.id === id);
const openShop = () => { const s = new ShopScene('barthens-provisions'); Game.push(s); return s; };
delete st.social;
check('old save begins neutral without mutation', localStanding(st, map).value === 0 && !st.social);
check('interior and street share standing', socialRegion('barthens-provisions') === socialRegion(map));
noteDeed(st, { kind: 'accept', questId: 'private-crime', tags: ['crime', 'theft'], mapId: map.id });
noteDeed(st, { kind: 'questFail', questId: 'private-crime', tags: ['abandoned', 'crime'], mapId: map.id });
check('accepting and abandoning a private criminal offer is not public wrongdoing', localStanding(st, map).value === 0);
let shop = openShop();
const base = buy(shop, 'explorers-pack').price;
check('unlimited staple remains available', buy(shop, 'rations').remaining === Infinity && !buy(shop, 'rations').disabled);
shop.msg = null; capture('neutral-shop'); Game.pop();
noteDeed(st, { kind: 'quest', questId: 'society-one', npcId: 'elmar-barthen', mapId: 'barthens-provisions', weight: 3 });
noteDeed(st, { kind: 'rescue', mapId: map.id, weight: 3 });
check('help builds trusted standing with daily cap', localStanding(st, map).value === 12);
noteDeed(st, { kind: 'rescue', mapId: map.id, weight: 5 });
check('repeat help cannot exceed daily cap', localStanding(st, map).value === 12);
check('standing remains local', localStanding(st, 'waterdeep').value === 0);
st.day++;
noteDeed(st, { kind: 'quest', questId: 'society-one', mapId: map.id, weight: 3 });
check('quest identity cannot be credited twice across days', localStanding(st, map).value === 12);
noteDeed(st, { kind: 'rescue', mapId: map.id, weight: 4 });
st.day++;
noteDeed(st, { kind: 'help', mapId: map.id, weight: 3 });
const villain = { id: 'redbrand-lookout', tag: 'villain', role: 'guard' };
check('a villain does not inherit civic gratitude', npcDisposition(st, villain, map) === 'neutral' && socialGreeting(st, villain, map) === null);
rememberNPC(st, villain.id, 'attacked');
check('villains still retain personal memories', npcDisposition(st, villain, map) === 'wary' && socialGreeting(st, villain, map).includes('weapon'));
const { getNPC } = await import('/src/data/npcs.js');
const astele = getNPC('astele-keene');
check('authored role-only villain exists', astele?.role === 'villain' && astele.tag !== 'villain');
check('role-only villains retain authored civic attitude', npcDisposition(st, astele, map) === 'neutral' && socialGreeting(st, astele, map) === null);
check('wrapped role-only villains retain authored civic attitude', npcDisposition(st, { id: astele.id, npc: astele }, map) === 'neutral' && socialGreeting(st, { id: astele.id, npc: astele }, map) === null);
shop = openShop();
check('respected locals get a ten percent goods discount', buy(shop, 'explorers-pack').price === Math.round(base * 0.9));
shop.msg = null; capture('respected-buy');
Party.addGold(2000);
const before = { gold: Party.gold, qty: Party.countItem('explorers-pack'), rep: localStanding(st, map).value };
const row = buy(shop, 'explorers-pack');
shop.qty = 1; shop._buy(row);
check('purchase charges quoted amount and adds exactly one item', Party.gold === before.gold - row.price && Party.countItem(row.id) === before.qty + 1);
check('purchase depletes finite stock', buy(shop, row.id).remaining === row.remaining - 1);
shop.tab = 1; shop._buildRows(); shop.msg = null; capture('respected-sell');
const sale = shop.rows.find(r => r.id === row.id);
shop._sell(sale); if (shop.prompt) shop._answer(0);
check('sale pays quoted amount and restores shelf space', Party.gold === before.gold - row.price + sale.price && buy(shop, row.id).remaining === row.remaining);
check('round trip earns neither money nor esteem', Party.gold <= before.gold && localStanding(st, map).value === before.rep);
check('merchant remembers customer', st.social.people['elmar-barthen'].customer);
// Adversarial explicitly priced clearance stock plus a premium buyback.
const custom = new ShopScene('probe', { stock: [{ id: 'explorers-pack', qty: 5, price: 1 }] });
custom.shop = { ...custom.shop, stock: [{ id: 'explorers-pack', qty: 5, price: 1 }], fill: null, buyback: 1 };
custom.tradeMult = 0.81; custom.standing = { sell: 1.1 };
Party.addItem('explorers-pack', 1);
check('explicit price and stacked discounts cannot create same-counter arbitrage', custom._sellRows().find(r => r.id === 'explorers-pack').price <= buy(custom, 'explorers-pack').price);
Party.addItem('potion-healing', 1);
// Use the actual lowest unlimited potion supplier from the catalogue.
const { SHOP_TABLES } = await import('/src/data/items.js');
let cheapest = Infinity;
for (const id of Object.keys(SHOP_TABLES)) {
  const counter = new ShopScene(id); counter.tradeMult = 0.81;
  const r = buy(counter, 'potion-healing');
  if (r && !r.limited) cheapest = Math.min(cheapest, r.price);
}
check('unlimited goods cannot be flipped across merchants for profit', custom._sellRows().find(r => r.id === 'potion-healing').price <= cheapest, { cheapest });
shop.tab = 2; shop._buildRows(); shop.msg = null; capture('services'); Game.pop();
const victim = { npcId: 'test-victim', id: 'spawn-victim', role: 'flavor' };
const witness = { npcId: 'test-witness', id: 'spawn-witness', role: 'guard' };
const repBefore = localStanding(st, map).value;
reportAssault(st, { map, npc: victim, entity: victim, witnesses: 0 });
check('unseen assault is personal, not town-wide knowledge', localStanding(st, map).value === repBefore && npcDisposition(st, victim, map) === 'wary');
reportAssault(st, { map, npc: victim, entity: victim, witnesses: 1, witnessEntities: [witness] });
check('witnessed assault reaches public standing and witness memory', localStanding(st, map).value === repBefore - 9 && st.social.people['test-witness'].witnessed);
payFine(st, map);
check('paying a fine does not erase memory', npcDisposition(st, witness, map) === 'wary');
const sight = witnessesNear([{ kind: 'npc', x: 1, y: 1 }, { kind: 'npc', x: 2, y: 1 }, { kind: 'npc', tag: 'animal', x: 1, y: 1 }], 3, 1, 7, null, { lineOfSight: x => x === 1 });
check('walls and animals cannot report assaults', sight.length === 1);
for (let i = 0; i < 8; i++) noteDeed(st, { kind: 'crime', mapId: map.id, weight: 3 });
check('negative standing is bounded', localStanding(st, map).value === -50);
shop = openShop(); shop.msg = null; capture('feared-shop');
check('distrusted trade terms apply after fine cleared', buy(shop, 'explorers-pack').price === Math.round(base * 1.2)); Game.pop();
const npc = new NPCEntity({ npcId: 'test-witness', id: 'spawn-witness', name: 'Watchman', role: 'guard', x: 20, y: 20, sprite: 'npc-guard', wander: 0 });
const dlg = new DialogueScene({ start: 'start', nodes: { start: { text: 'The road to Neverwinter is open.', choices: [{ text: 'Farewell.', end: true }] } } }, npc);
Game.push(dlg); dlg.shown = 10000; capture('witness-remembers');
check('memory precedes authored dialogue without deleting it', dlg.pages.length === 2 && dlg.npcId === 'test-witness'); Game.pop();
const field = new TileMap({ id: 'society-field', w: 30, h: 30 });
const walker = new NPCEntity({ npcId: 'test-walker', x: 10, y: 10, wander: 1, wanderChance: 0 });
walker.flee(9, 10, 1);
for (let i = 0; i < 300; i++) walker.update(0.05, field, { player: { x: 25, y: 25 } });
check('panic ends and civilian returns to home', walker.x === 10 && walker.y === 10 && !walker.returningHome, { x: walker.x, y: walker.y });
rememberNPC(st, 'test-walker', 'witnessed');
for (let i = 0; i < 120; i++) walker.update(0.05, field, { player: { x: 9, y: 10 } });
const held = { x: walker.x, y: walker.y };
for (let i = 0; i < 120; i++) walker.update(0.05, field, { player: { x: 9, y: 10 } });
check('wary civilian keeps distance without oscillation', walker.distanceTo(9, 10) >= 3 && walker.x === held.x && walker.y === held.y, held);
const guard = new NPCEntity({ npcId: 'test-witness', role: 'guard', x: 10, y: 10, wander: 1 });
guard.think(1, field, { player: { x: 9, y: 10 } });
check('wary guard watches without abandoning post', guard.x === 10 && guard.y === 10 && guard.dir === 'left');
const obstructed = new NPCEntity({ npcId: 'test-walker', x: 10, y: 10, wander: 1, wanderChance: 0 });
field.flags[field.idx(9, 10)] = TF.SOLID;
obstructed.think(0.1, field, { player: { x: 8, y: 10 } });
check('wary civilian does not retreat or turn through walls', !obstructed.moving && obstructed.dir === 'down');
obstructed.home = { x: 15, y: 10 }; obstructed.returningHome = true;
obstructed.think(0.1, field, { player: { x: 8, y: 10 } });
check('an unseen party does not interrupt return-home pathfinding', obstructed.path?.length > 0);
field.flags[field.idx(9, 10)] = 0;
check('animals receive no human memory greeting', socialGreeting(st, { id: 'dog', tag: 'animal' }, map) === null);
const saved = Save.write(4, st), loaded = Save.read(4);
check('save round trip retains memory and standing', saved.ok && loaded.social.people['test-witness'].witnessed && localStanding(loaded, map).value === -50);
return [...shots, { id: 'checks', checks }];
