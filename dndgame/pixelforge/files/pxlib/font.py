GLYPH_W = 3
GLYPH_H = 5
_UNKNOWN = (7, 7, 7, 7, 7)


def glyph(ch):
    if ch in _G:
        return _G[ch]
    up = ch.upper()
    return _G.get(up, _UNKNOWN)


def text_width(s, scale=1, tracking=1):
    if not s:
        return 0
    return (len(s) * (GLYPH_W + tracking) - tracking) * scale


def text_height(scale=1):
    return GLYPH_H * scale
